template<class FlagIsSet>
bool HasReadEvidence(std::string_view item, std::string_view reader, int ironbeardProgress, FlagIsSet flagIsSet) {
    constexpr std::string_view ironbeardItems[]{
        "ITWR_EISENBARTSDOKUMENT", "ITWR_EISENBARTSDOKUMENT2", "ITWR_EISENBARTSDOKUMENT3"
    };
    constexpr std::string_view ironbeardReaders[]{
        "USE_EISENBARTSDOKUMENT", "USE_EISENBARTSDOKUMENT2", "USE_EISENBARTSDOKUMENT3"
    };
    if (ironbeardProgress >= 1 && ironbeardProgress <= 3) {
        for (int i = 0; i < ironbeardProgress; ++i) {
            if (item == ironbeardItems[i] && reader == ironbeardReaders[i]) return true;
        }
    }
    const auto end = rules + sizeof(rules) / sizeof(rules[0]);
    for (auto rule = std::lower_bound(rules, end, item, [](const Rule& entry, std::string_view name) {
        return entry.item < name;
    }); rule != end && rule->item == item; ++rule) {
        if (rule->reader == reader && flagIsSet(rule->flag)) return true;
    }
    return false;
}

